"""Command line entry point: python -m pumpsim {serve,scenarios,faults}."""

from __future__ import annotations

import argparse
import sys

from .faults import CATALOG


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="pumpsim", description="Infusion pump hardware simulator")
    parser.add_argument("--firmware", help="path to pump_firmware (default: build/firmware/pump_firmware)")
    sub = parser.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("serve", help="run the service and touchscreen UI")
    s.add_argument("--host", default="127.0.0.1")
    s.add_argument("--port", type=int, default=8000)
    s.add_argument("--speed", type=int, default=1, choices=(1, 2, 5, 10, 20))

    r = sub.add_parser("scenarios", help="run every fault scenario and print the response table")
    r.add_argument("--markdown", help="also write the table to this file")

    sub.add_parser("faults", help="list injectable faults")

    args = parser.parse_args(argv)
    if args.cmd == "serve":
        from .service import serve

        serve(args.host, args.port, args.firmware, args.speed)
        return 0
    if args.cmd == "faults":
        for f in CATALOG:
            print(f"{f.id:22} {f.group:14} {f.label}")
        return 0
    if args.cmd == "scenarios":
        from .scenarios import run_all, to_markdown

        results = run_all(args.firmware)
        table = to_markdown(results)
        print(table)
        if args.markdown:
            with open(args.markdown, "w", encoding="utf-8") as fh:
                fh.write("# Fault response report\n\n")
                fh.write("Generated by `python -m pumpsim scenarios`. Each scenario programs saline, primes,\n")
                fh.write("starts the infusion, waits 5 s, injects the fault and measures simulated time\n")
                fh.write("until the expected alarm is annunciated.\n\n")
                fh.write(table + "\n")
        return 0 if all(r.passed for r in results) else 1
    return 2  # pragma: no cover


if __name__ == "__main__":
    sys.exit(main())
